#!/usr/bin/env python3
"""Embed the Pixel Agents furniture PNGs as palette-indexed strings.

The app draws them from pixel data, so no image URLs (and no CSP questions)
are involved. Run after changing anything in assets/pixel-agents/furniture:

    python3 scripts/embed-pixel-agents.py
"""
import glob
import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "pixel-agents", "furniture")
OUT = os.path.join(ROOT, "office", "pixelAgents.generated.ts")
ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

sprites = {}
for path in sorted(glob.glob(os.path.join(SRC, "*", "*.png"))):
    name = os.path.splitext(os.path.basename(path))[0]
    im = Image.open(path).convert("RGBA")
    colors = {c for c in im.getdata() if c[3] >= 128}
    if len(colors) > len(ALPHABET) - 1:
        # A few paintings have more colors than one character can index.
        alpha = im.getchannel("A")
        im = im.convert("RGB").quantize(len(ALPHABET) - 1).convert("RGBA")
        im.putalpha(alpha)
    w, h = im.size
    px = im.load()
    pal = []
    out = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a < 128:
                out.append(".")
                continue
            c = "#%02x%02x%02x" % (r, g, b)
            if c not in pal:
                pal.append(c)
            out.append(ALPHABET[pal.index(c)])
    assert len(pal) <= len(ALPHABET), name
    sprites[name] = {"w": w, "h": h, "pal": pal, "px": "".join(out)}

with open(OUT, "w") as f:
    f.write("// Generated by scripts/embed-pixel-agents.py from assets/pixel-agents (MIT, see ATTRIBUTION.md).\n")
    f.write("// Do not edit by hand.\n\n")
    f.write("export interface PackedSprite {\n  w: number;\n  h: number;\n  pal: string[];\n  px: string;\n}\n\n")
    f.write("export const PIXEL_AGENTS: Record<string, PackedSprite> = ")
    f.write(json.dumps(sprites, separators=(",", ":")))
    f.write(";\n")
print(f"{len(sprites)} sprites -> {OUT} ({os.path.getsize(OUT)} bytes)")
